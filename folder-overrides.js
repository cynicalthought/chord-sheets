    let categoryKey = category;
    if (categoryKey === 'composer') categoryKey = 'composers';
    if (categoryKey === 'artist') categoryKey = 'artists';
    if (categoryKey === 'lyricist') categoryKey = 'lyricists';

    if (categoryKey && window.FOLDER_OVERRIDES[categoryKey] && window.FOLDER_OVERRIDES[categoryKey][name]) {
        return window.FOLDER_OVERRIDES[categoryKey][name];
    }
    
    for (let cat in window.FOLDER_OVERRIDES) {
        if (window.FOLDER_OVERRIDES[cat] && window.FOLDER_OVERRIDES[cat][name]) {
            return window.FOLDER_OVERRIDES[cat][name];
        }
    }
    return name;
